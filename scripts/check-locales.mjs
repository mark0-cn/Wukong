import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { parse } from '@fluent/syntax';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = locale => {
  const messages = new Map();
  for (const file of readdirSync(`${root}locales/${locale}`).filter(f => f.endsWith('.ftl'))) {
    const ast = parse(readFileSync(`${root}locales/${locale}/${file}`, 'utf8'));
    for (const entry of ast.body) {
      if (entry.type === 'Junk') throw Error(`${locale}/${file}: ${entry.annotations.map(a => a.message)}`);
      if (entry.type !== 'Message' && entry.type !== 'Term') continue;
      const id = entry.id.name;
      if (messages.has(id)) throw Error(`${locale}: duplicate ${id}`);
      const variables = new Set();
      const walk = node => {
        if (!node || typeof node !== 'object') return;
        if (node.type === 'VariableReference') variables.add(node.id.name);
        for (const value of Object.values(node)) if (Array.isArray(value)) value.forEach(walk); else walk(value);
      };
      walk(entry);
      messages.set(id, [...variables].sort());
    }
  }
  return Object.fromEntries([...messages].sort(([a], [b]) => a.localeCompare(b, 'en')));
};
const en = read('en-US'), zh = read('zh-CN');
if (JSON.stringify(en) !== JSON.stringify(zh)) throw Error('Locale keys or interpolation variables differ');
const generated = '// Generated by scripts/check-locales.mjs --write. Do not edit.\nexport interface Messages {\n' +
  Object.entries(en).map(([id, variables]) => `  '${id}': ${variables.length ? `{ ${variables.map(v => `${v}: string | number`).join('; ')} }` : 'undefined'};`).join('\n') + '\n}\n';
const destination = `${root}ui/src/i18n/messages.ts`;
if (process.argv.includes('--write')) writeFileSync(destination, generated);
else if (readFileSync(destination, 'utf8').replaceAll('\r\n', '\n') !== generated) throw Error('Run node scripts/check-locales.mjs --write');
console.log(`Validated ${Object.keys(en).length} messages in two locales.`);
