import { currentLocale, t, useLocale } from '../../shared/i18n';
import { useEffect, useId, useRef, useState } from 'react';
import { api, errorText, errorValue } from '../../shared/api/bridge';
import type {
  WorkerMediaGeneration, WorkerMediaImportResult, WorkerMediaInstallation,
  WorkerMediaNetwork, WorkerMediaStatus,
} from '../../shared/api/commands';
import { displayPath } from '../../shared/lib/displayPath';
import { Modal } from '../../shared/ui/Modal';

type Failure = ReturnType<typeof errorValue>;
type Dialog = 'generate' | 'import';

/** Identifiers published inside the generated media (data, not translatable copy). */
const SETUP_EXECUTABLE = 'WukongWorkerSetup.exe';
const RECEIPT_FILENAME = 'connection.json';
const MAX_RECEIPT_BYTES = 16 * 1024;

const failureDetail = (failure: Failure) => typeof failure === 'string' ? failure : failure.detail ?? '';

/** Map the stable backend failure phrases to an actionable localized hint. */
function failureHint(failure: Failure): string | undefined {
  const detail = failureDetail(failure);
  if (detail.includes('does not publish a Windows worker media template')) return t('windows-worker-template-unavailable');
  if (detail.includes('none of the saved address candidates')) return t('windows-worker-import-failed-address');
  if (detail.includes('different worker host key') || detail.includes('different SSH enrollment settings')) return t('windows-worker-import-failed-host-key');
  if (detail.includes('not generated by this controller') || detail.includes('not this installation task')) return t('windows-worker-import-failed-foreign');
  if (detail.includes('multiple IPv4 management networks')) return t('windows-worker-network-multiple');
  return undefined;
}

function useElapsed(active: boolean) {
  const [seconds, setSeconds] = useState(0);
  useEffect(() => {
    if (!active) { setSeconds(0); return; }
    const started = Date.now();
    const timer = window.setInterval(() => setSeconds(Math.floor((Date.now() - started) / 1000)), 1000);
    return () => window.clearInterval(timer);
  }, [active]);
  return seconds;
}

const stateLabel = (state: WorkerMediaStateView) => state === 'available' ? t('windows-worker-state-available')
  : state === 'installed_pending' ? t('windows-worker-state-pending') : t('windows-worker-state-generated');
const stateClass = (state: WorkerMediaStateView) => state === 'available' ? 'status-completed'
  : state === 'installed_pending' ? 'status-waiting' : 'status-queued';
type WorkerMediaStateView = WorkerMediaInstallation['state'];
const cidrOf = (network: WorkerMediaNetwork) => `${network.ipv4}/${network.prefix_len}`;
const networkLabel = (network: WorkerMediaNetwork) => `${network.name} — ${cidrOf(network)}${network.recommended ? ` · ${t('windows-worker-network-recommended')}` : ''}`;

function FailureNote({ error }: { error: Failure }) {
  const hint = failureHint(error);
  return <div className="worker-failure"><p className="error" role="alert">{errorText(error)}</p>{hint && <p className="muted">{hint}</p>}</div>;
}

export function WindowsWorker({ epoch, disabled = false, onRegistered }: {
  epoch: number; disabled?: boolean; onRegistered: () => void;
}) {
  useLocale();
  const [status, setStatus] = useState<WorkerMediaStatus>();
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<Failure>('');
  const [notice, setNotice] = useState('');
  const [revision, setRevision] = useState(0);
  const [dialog, setDialog] = useState<Dialog>();
  const [retrying, setRetrying] = useState<string>();
  useEffect(() => {
    let alive = true;
    setLoading(true);
    void api('worker_media_status', { epoch }).then(value => {
      if (!alive) return;
      setStatus(value); setError('');
    }).catch(cause => { if (alive) setError(errorValue(cause)); })
      .finally(() => { if (alive) setLoading(false); });
    return () => { alive = false; };
  }, [epoch, revision]);
  const refresh = () => setRevision(value => value + 1);
  const retry = async (installation: WorkerMediaInstallation) => {
    if (disabled || retrying) return;
    setRetrying(installation.installation_id); setError(''); setNotice('');
    try {
      const result = await api('worker_media_retry', { epoch, installationId: installation.installation_id });
      if (result.state === 'available') {
        setNotice(t('windows-worker-import-available-notice', { address: result.address ?? '' }));
        onRegistered();
      } else {
        setNotice(t('windows-worker-import-pending-notice'));
        refresh();
      }
    } catch (cause) { setError(errorValue(cause)); }
    finally { setRetrying(undefined); }
  };
  const generated = (generation: WorkerMediaGeneration) => {
    setDialog(undefined);
    setNotice(t('windows-worker-generated-notice', { path: displayPath(generation.zip_path) }));
    refresh();
  };
  const imported = (result: WorkerMediaImportResult) => {
    setDialog(undefined);
    if (result.state === 'available') {
      setNotice(t('windows-worker-import-available-notice', { address: result.address ?? '' }));
      onRegistered();
    } else {
      setNotice(t('windows-worker-import-pending-notice'));
      refresh();
    }
  };
  const installations = status?.installations ?? [];
  const busy = Boolean(retrying);
  return <section className="settings-group worker-card" aria-label={t('windows-worker-title')}>
    <h3>{t('windows-worker-title')}</h3>
    <p className="muted">{t('windows-worker-description')}</p>
    <p className="muted">{t('windows-worker-description-note')}</p>
    <div className="header-actions worker-actions">
      <button type="button" className="primary" disabled={disabled || busy} onClick={() => { setNotice(''); setError(''); setDialog('generate'); }}>
        {t('windows-worker-generate')}
      </button>
      <button type="button" className="primary" disabled={disabled || busy || !installations.length} onClick={() => { setNotice(''); setError(''); setDialog('import'); }}>
        {t('windows-worker-import')}
      </button>
    </div>
    {notice && <p role="status" className="worker-notice">{notice}</p>}
    {error && <FailureNote error={error} />}
    {loading && !status && <p className="muted" role="status">{t('windows-worker-loading')}</p>}
    {status && !installations.length && !loading && <p className="muted">{t('windows-worker-empty')}</p>}
    {installations.length > 0 && <div className="worker-installations">
      {installations.map(installation => <article key={installation.installation_id} className="worker-installation">
        <header className="worker-installation-head">
          <div><strong>{installation.registered_environment_name ?? installation.environment_name}</strong>
            <small>{installation.environment_id} · v{installation.app_version} · {new Date(installation.created_at).toLocaleString(currentLocale())}</small></div>
          <span className={`status ${stateClass(installation.state)}`}>{stateLabel(installation.state)}</span>
        </header>
        {installation.warning && <p className="worker-warning">{installation.warning}</p>}
        <div className="worker-facts">
          <div><span>{t('windows-worker-package')}</span><strong title={installation.zip_path} className="path">{displayPath(installation.zip_path)}</strong></div>
          <div><span>{t('windows-worker-ssh-port')}</span><strong>{installation.ssh_port}</strong></div>
          <div><span>{t('windows-worker-network')}</span><strong>{installation.management_peer}/{installation.network_prefix_len}</strong></div>
        </div>
        {!installation.zip_present && <p className="muted">{t('windows-worker-package-missing')}</p>}
        {installation.state === 'generated' && <details className="worker-instructions" open>
          <summary>{t('windows-worker-instructions')}</summary>
          <ol>
            <li>{t('windows-worker-step-copy')}</li>
            <li>{t('windows-worker-step-run', { executable: SETUP_EXECUTABLE })}</li>
            <li>{t('windows-worker-step-confirm', { receipt: RECEIPT_FILENAME })}</li>
            <li>{t('windows-worker-step-import')}</li>
          </ol>
          {!installation.media_present && <p className="muted">{t('windows-worker-media-missing')}</p>}
          <button type="button" disabled={disabled || busy} onClick={() => { setNotice(''); setError(''); setDialog('import'); }}>{t('windows-worker-import')}</button>
        </details>}
        {installation.state === 'installed_pending' && <>
          <p>{t('windows-worker-pending-help')}</p>
          {installation.candidate_addresses.length > 0 && <p className="muted">{t('windows-worker-candidates', { addresses: installation.candidate_addresses.join(', ') })}</p>}
          {installation.last_address && <p className="muted">{t('windows-worker-last-address', { address: installation.last_address })}</p>}
          <p className="muted">{t('windows-worker-pending-address-help')}</p>
          <button type="button" disabled={disabled || busy} onClick={() => void retry(installation)}>
            {retrying === installation.installation_id ? t('windows-worker-retrying') : t('windows-worker-retry-connection')}
          </button>
          {retrying === installation.installation_id && <div className="worker-progress" role="status">
            <progress aria-label={t('windows-worker-progress-label')} /><p>{t('windows-worker-retrying')}</p></div>}
        </>}
        {installation.state === 'available' && <>
          {installation.registered_environment_id && <p>{t('windows-worker-registered-environment', {
            environment: installation.registered_environment_name ?? installation.environment_name,
            id: installation.registered_environment_id,
          })}</p>}
          <p className="muted">{t('windows-worker-rename-note')}</p>
        </>}
      </article>)}
    </div>}
    {dialog === 'generate' && <GenerateDialog epoch={epoch} disabled={disabled} onCancel={() => setDialog(undefined)} onGenerated={generated} />}
    {dialog === 'import' && <ImportDialog epoch={epoch} installations={installations} disabled={disabled} onCancel={() => setDialog(undefined)} onImported={imported} />}
  </section>;
}

function GenerateDialog({ epoch, disabled, onCancel, onGenerated }: {
  epoch: number; disabled: boolean; onCancel: () => void; onGenerated: (generation: WorkerMediaGeneration) => void;
}) {
  const fieldId = useId();
  const [networks, setNetworks] = useState<WorkerMediaNetwork[]>();
  const [networksLoading, setNetworksLoading] = useState(true);
  const [networkError, setNetworkError] = useState<Failure>('');
  const [networkId, setNetworkId] = useState('');
  const [output, setOutput] = useState('');
  const [name, setName] = useState('');
  const [template, setTemplate] = useState('');
  const [error, setError] = useState<Failure>('');
  const [generating, setGenerating] = useState(false);
  const elapsed = useElapsed(generating);
  const loadNetworks = async () => {
    setNetworksLoading(true); setNetworkError('');
    try {
      const value = await api('worker_media_networks');
      const initial = value.find(network => network.recommended) ?? value[0];
      setNetworks(value);
      setNetworkId(previous => previous || (initial ? cidrOf(initial) : ''));
    } catch (cause) { setNetworkError(errorValue(cause)); }
    finally { setNetworksLoading(false); }
  };
  useEffect(() => { void loadNetworks(); }, []);
  const chooseOutput = async () => {
    try { const path = await api('pick_worker_output'); if (path) setOutput(path); }
    catch (cause) { setError(errorValue(cause)); }
  };
  const chooseTemplate = async () => {
    try { const path = await api('pick_worker_template'); if (path) { setTemplate(path); setError(''); } }
    catch (cause) { setError(errorValue(cause)); }
  };
  const selected = networks?.length === 1 ? networks[0] : networks?.find(network => cidrOf(network) === networkId);
  const ready = !disabled && !generating && Boolean(output) && Boolean(networks?.length) && Boolean(selected);
  const generate = async () => {
    if (!ready) return;
    setGenerating(true); setError('');
    try {
      const value = await api('worker_media_generate', {
        epoch, output,
        ...(template ? { template } : {}),
        ...(name.trim() ? { environmentName: name.trim() } : {}),
        ...(networks && networks.length > 1 && networkId ? { network: networkId } : {}),
      });
      onGenerated(value);
    } catch (cause) { setError(errorValue(cause)); }
    finally { setGenerating(false); }
  };
  return <Modal title={t('windows-worker-generate-title')} description={t('windows-worker-generate-description')} wide onClose={() => { if (!generating) onCancel(); }}>
    <fieldset disabled={disabled || generating} className="connection-fields">
      <legend className="sr-only">{t('windows-worker-generate-title')}</legend>
      <label className="field"><span>{t('windows-worker-name')}</span>
        <input id={`${fieldId}-name`} value={name} placeholder={t('windows-worker-name-placeholder')} autoComplete="off" onChange={event => setName(event.target.value)} />
        <small>{t('windows-worker-name-help')}</small></label>
      <div className="field"><span>{t('windows-worker-template')}</span>
        {template ? <>
          <code className="path">{displayPath(template)}</code>
          <button type="button" onClick={() => setTemplate('')}>{t('windows-worker-template-release')}</button>
        </> : <>
          <p className="muted">{t('windows-worker-template-default')}</p>
          <button type="button" onClick={() => void chooseTemplate()}>{t('windows-worker-template-local')}</button>
        </>}
      </div>
      <div className="field"><span>{t('windows-worker-output')}</span>
        <span className="connection-key-picker">
          <input readOnly value={output ? displayPath(output) : ''} placeholder={t('windows-worker-output-placeholder')} aria-label={t('windows-worker-output')} />
          <button type="button" onClick={() => void chooseOutput()}>{t('windows-worker-choose-output')}</button>
        </span>
      </div>
      <div className="field"><span>{t('windows-worker-network')}</span>
        {networksLoading ? <p className="muted" role="status">{t('windows-worker-network-loading')}</p>
          : networkError ? <div><p className="error" role="alert">{errorText(networkError)}</p><button type="button" onClick={() => void loadNetworks()}>{t('windows-worker-retry-load')}</button></div>
          : !networks?.length ? <p className="error">{t('windows-worker-network-none')}</p>
          : networks.length === 1 ? <p className="muted">{t('windows-worker-network-single', { network: networkLabel(networks[0]) })}</p>
          : <><select aria-label={t('windows-worker-network')} value={networkId} onChange={event => setNetworkId(event.target.value)}>
            {networks.map(network => <option key={cidrOf(network)} value={cidrOf(network)}>{networkLabel(network)}</option>)}
          </select><small>{t('windows-worker-network-help')}</small></>}
      </div>
      {generating && <div className="worker-progress" role="status">
        <progress aria-label={t('windows-worker-progress-label')} />
        <p>{t('windows-worker-generating')}</p>
        <p className="muted">{t('windows-worker-generate-stages')} · {t('windows-worker-elapsed', { seconds: elapsed })}</p>
      </div>}
      {error && <FailureNote error={error} />}
    </fieldset>
    <div className="modal-footer">
      <button type="button" disabled={generating} onClick={onCancel}>{t('windows-worker-cancel')}</button>
      <button type="button" className="primary" disabled={!ready} onClick={() => void generate()}>{generating ? t('windows-worker-working') : t('windows-worker-generate-action')}</button>
    </div>
  </Modal>;
}

function ImportDialog({ epoch, installations, disabled, onCancel, onImported }: {
  epoch: number; installations: WorkerMediaInstallation[]; disabled: boolean;
  onCancel: () => void; onImported: (result: WorkerMediaImportResult) => void;
}) {
  const fieldId = useId();
  const receiptInput = useRef<HTMLInputElement>(null);
  const [receipt, setReceipt] = useState('');
  const [receiptName, setReceiptName] = useState('');
  const [receiptFingerprint, setReceiptFingerprint] = useState('');
  const [confirmed, setConfirmed] = useState('');
  const [name, setName] = useState('');
  const [reading, setReading] = useState(false);
  const [importing, setImporting] = useState(false);
  const [error, setError] = useState<Failure>('');
  const busy = reading || importing;
  const matches = Boolean(receiptFingerprint && confirmed.trim() === receiptFingerprint);
  const ready = Boolean(receipt) && matches && !busy && !disabled;
  const load = async (file: File) => {
    setError(''); setReceipt(''); setReceiptName(''); setReceiptFingerprint(''); setConfirmed('');
    if (file.size > MAX_RECEIPT_BYTES) { setError(t('windows-worker-receipt-too-large')); return; }
    setReading(true);
    try {
      const text = (await file.text()).replace(/^\uFEFF/, '');
      let value: unknown;
      try { value = JSON.parse(text); } catch { setError(t('windows-worker-receipt-invalid')); return; }
      const record = value && typeof value === 'object' ? value as Record<string, unknown> : {};
      const fingerprint = typeof record.host_fingerprint === 'string' ? record.host_fingerprint : '';
      if (!fingerprint) { setError(t('windows-worker-receipt-invalid')); return; }
      setReceipt(text); setReceiptName(file.name); setReceiptFingerprint(fingerprint);
      const installationId = typeof record.installation_id === 'string' ? record.installation_id : '';
      const match = installations.find(entry => entry.installation_id === installationId);
      if (match) setName(match.environment_name);
    } catch (cause) { setError(errorValue(cause)); }
    finally { setReading(false); }
  };
  const submit = async () => {
    if (!ready) return;
    setImporting(true); setError('');
    try {
      const result = await api('worker_media_import', {
        epoch, receipt, confirmedFingerprint: confirmed.trim(),
        ...(name.trim() ? { name: name.trim() } : {}),
      });
      onImported(result);
    } catch (cause) { setError(errorValue(cause)); }
    finally { setImporting(false); }
  };
  return <Modal title={t('windows-worker-import-title')} description={t('windows-worker-import-description')} onClose={() => { if (!busy) onCancel(); }}>
    <fieldset disabled={disabled || busy} className="connection-fields">
      <legend className="sr-only">{t('windows-worker-import-title')}</legend>
      <div className="field"><span>{t('windows-worker-receipt')}</span>
        <input ref={receiptInput} className="sr-only" aria-label={t('windows-worker-receipt')} type="file" accept=".json,application/json" onChange={event => {
          const file = event.target.files?.[0];
          event.target.value = '';
          if (file) void load(file);
        }} />
        <span className="connection-key-picker">
          <button type="button" onClick={() => receiptInput.current?.click()}>{t('windows-worker-choose-receipt')}</button>
          <small>{receiptName ? t('windows-worker-receipt-loaded', { name: receiptName }) : t('windows-worker-receipt-empty')}</small>
        </span>
      </div>
      {reading && <p className="muted" role="status">{t('windows-worker-receipt-reading')}</p>}
      {receiptFingerprint && <p className="connection-fingerprint"><span>{t('windows-worker-receipt-fingerprint')}</span><code>{receiptFingerprint}</code></p>}
      <div className="field"><label htmlFor={`${fieldId}-fingerprint`}>{t('windows-worker-confirm-fingerprint')}</label>
        <input id={`${fieldId}-fingerprint`} aria-describedby={`${fieldId}-fingerprint-help`} value={confirmed} spellCheck={false} autoComplete="off" placeholder="SHA256:…" onChange={event => setConfirmed(event.target.value)} />
        <small id={`${fieldId}-fingerprint-help`}>{t('windows-worker-confirm-fingerprint-help', { receipt: RECEIPT_FILENAME })}</small></div>
      {confirmed && !matches && <p className="error" role="alert">{t('windows-worker-fingerprint-mismatch')}</p>}
      <label className="field"><span>{t('windows-worker-import-name')}</span>
        <input value={name} placeholder={t('windows-worker-import-name-placeholder')} onChange={event => setName(event.target.value)} />
        <small>{t('windows-worker-import-name-help')}</small></label>
    </fieldset>
    {importing && <div className="worker-progress" role="status">
      <progress aria-label={t('windows-worker-progress-label')} /><p>{t('windows-worker-importing')}</p></div>}
    {error && <FailureNote error={error} />}
    <div className="modal-footer">
      <button type="button" disabled={busy} onClick={onCancel}>{t('windows-worker-cancel')}</button>
      <button type="button" className="primary" disabled={!ready} onClick={() => void submit()}>{importing ? t('windows-worker-working') : t('windows-worker-import-action')}</button>
    </div>
  </Modal>;
}
