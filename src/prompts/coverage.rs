//! Maintenance metadata. Associations do not grant permissions or claim solve rates.
use crate::agents::SkillManifest;
use std::{collections::BTreeMap, sync::LazyLock};

pub(crate) fn builtins() -> &'static BTreeMap<String, SkillManifest> {
    static COVERAGE: LazyLock<BTreeMap<String, SkillManifest>> = LazyLock::new(|| {
        serde_json::from_str(include_str!("../../prompts/coverage.json"))
            .expect("checked built-in skill coverage")
    });
    &COVERAGE
}

pub(crate) fn markdown() -> anyhow::Result<String> {
    let catalog = crate::agents::skill_catalog(None)?;
    let mut output = String::from(
        "# Skill coverage\n\nGenerated by `wukong skill-catalog`. Associations are maintenance metadata, not permissions or runtime availability. Fixture links describe mechanism/control coverage, not original WP reproduction or Agent accuracy. Unregistered coverage means no association is recorded, not that the skill is unsupported.\n\n| Skill | Related tools | Sources | Mechanism fixtures |\n|---|---|---|---|\n",
    );
    for entry in catalog.as_array().expect("skill catalog array") {
        let metadata: SkillManifest = serde_json::from_value(entry["metadata"].clone())?;
        let tools = metadata
            .related_tools
            .iter()
            .map(|name| format!("`{name}`"))
            .collect::<Vec<_>>()
            .join(", ");
        let sources = metadata
            .sources
            .iter()
            .map(|path| format!("[{path}](../../{path})"))
            .collect::<Vec<_>>()
            .join(", ");
        let fixtures = metadata
            .fixtures
            .iter()
            .map(|id| format!("[{id}](../../fixtures/pwn/tasks.json)"))
            .collect::<Vec<_>>()
            .join(", ");
        output.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            entry["name"].as_str().unwrap(),
            if tools.is_empty() {
                "Unregistered"
            } else {
                &tools
            },
            if sources.is_empty() {
                "Unregistered"
            } else {
                &sources
            },
            if fixtures.is_empty() {
                "Unregistered"
            } else {
                &fixtures
            }
        ));
    }
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{collections::BTreeSet, path::Path};

    #[test]
    fn associations_resolve_to_registered_methods_tools_sources_and_cases() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let tools: BTreeSet<_> = crate::tools::builtin_tool_definitions()
            .into_iter()
            .map(|tool| tool.name.to_string())
            .collect();
        let tasks: serde_json::Value =
            serde_json::from_str(include_str!("../../fixtures/pwn/tasks.json")).unwrap();
        let cases: BTreeSet<_> = tasks["cases"]
            .as_array()
            .unwrap()
            .iter()
            .map(|case| format!("pwn/{}", case["id"].as_str().unwrap()))
            .collect();
        for (name, coverage) in builtins() {
            let entry = crate::prompts::find(name).expect("coverage owner missing");
            assert!(!matches!(entry.kind, crate::prompts::Kind::Role(_)));
            assert!(
                coverage
                    .related_tools
                    .iter()
                    .all(|tool| tools.contains(tool)),
                "unknown tool for {name}"
            );
            assert!(
                coverage
                    .sources
                    .iter()
                    .all(|source| root.join(source).is_file()),
                "unknown source for {name}"
            );
            assert!(
                coverage.fixtures.iter().all(|case| cases.contains(case)),
                "unknown fixture for {name}"
            );
        }
    }

    #[test]
    fn replacing_builtin_content_does_not_inherit_its_fixture_claims() {
        let directory = tempfile::tempdir().unwrap();
        std::fs::write(directory.path().join("fsop.md"), "Custom method").unwrap();
        let catalog = crate::agents::skill_catalog(Some(directory.path())).unwrap();
        let entry = catalog
            .as_array()
            .unwrap()
            .iter()
            .find(|entry| entry["name"] == "fsop")
            .unwrap();
        assert_eq!(entry["source"], "custom");
        assert!(entry["metadata"]["fixtures"].as_array().unwrap().is_empty());
    }
}
